# 2. electronic_shift.md
electronic_shift_content = """# Электронный селектор переключения передач (Shift-by-Wire)

> **Страницы в оригинале:** 531 – 565 | **Модель:** Changan CS55 Plus (Второе поколение)

## 1. Устройство электронного селектора в салоне

В автомобиле Changan CS55 Plus реализовано полностью электронное переключение режимов трансмиссии без механической связи (троса):
* Селектор выполнен в виде эргономичного джойстика нефиксируемого типа (моностабильного).
* Перемещение джойстика назад переводит коробку в режим **D (Drive)**.
* Перемещение джойстика вперед с нажатием боковой клавиши блокировки переводит коробку в режим **R (Задний ход)**.
* Кратковременное качание вперед переводит коробку в **N (Нейтраль)**.
* Отдельная клавиша **P (Паркинг)** со встроенным светодиодным индикатором расположена на верхней части ручки.

---

## 2. Логика автоматической защиты от ошибок водителя

Электронная система Shift-by-Wire включает автоматические алгоритмы безопасности:
1. **Автоматический паркинг (Auto P):** если автомобиль остановился, двигатель заглушен кнопкой Start/Stop или водитель открыл свою дверь при отстегнутом ремне безопасности в режиме D/R, блок TCU **автоматически переводит трансмиссию в режим P** и затягивает стояночный тормоз EPB.
2. **Защита от случайного включения заднего хода на скорости:** при попытке перевести селектор в R на скорости более 10 км/ч вперед коробка проигнорирует команду, выдаст звуковой сигнал и останется на текущей передаче.

---

## 3. Аварийная разблокировка режима P (Паркинг) для эвакуации

При полном разряде аккумулятора или выходе из строя электроники сервопривод паркинга остается заблокированным.

### Порядок механической аварийной разблокировки:
1. Поднимите капот автомобиля.
2. Снимите корпус воздушного фильтра для доступа к верхней плоскости коробки передач.
3. На картере трансмиссии найдите металлический рычаг аварийной разблокировки механизма парковки (обозначен гравировкой **P-UNLOCK**).
4. Рожковым ключом или отверткой поверните рычаг против часовой стрелки до щелчка и зафиксируйте его шплинтом/фиксатором.
5. Трансмиссия перейдет в нейтральное положение (N), и автомобиль можно будет свободно закатить на платформу эвакуатора.
"""

